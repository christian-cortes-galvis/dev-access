export function iconSvg(name, cls) {
  const body = PATHS[name] || PATHS.gauge;
  const klass = cls ? ` class="${cls}"` : '';
  return `<svg${klass} viewBox="0 0 24 24" fill="none" stroke="currentColor" ` +
    `stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">${body}</svg>`;
}

export function iconEl(name, cls) {
  const span = document.createElement('span');
  span.className = 'd-inline-flex align-items-center';
  span.innerHTML = iconSvg(name, cls);
  return span;
}

export function applyDataIcons(root) {
  (root || document).querySelectorAll('[data-icon]').forEach((node) => {
    if (node.dataset.iconDone) return;
    const name = node.getAttribute('data-icon');
    node.insertAdjacentHTML('afterbegin', iconSvg(name));
    node.dataset.iconDone = '1';
  });
}

